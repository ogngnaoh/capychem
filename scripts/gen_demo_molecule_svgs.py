"""Generate real RDKit 2D depictions for the demo's molecules, byte-identical to the
live GET /molecule/svg endpoint (same render_svg). Writes a generated TS module the
Playwright fixtures import. N6: these are in-silico structures, no efficacy claim.

Run: uv run python scripts/gen_demo_molecule_svgs.py
"""

from __future__ import annotations

import json
from pathlib import Path

from capychem.api.routes_molecule import render_svg

# The 9 distinct SMILES the demo renders (TOP_K + Compare GA-268 top_k). Keep in sync
# with apps/web/e2e/_fixtures.ts if those fixtures change.
SMILES = [
    "CC(C)C[C@H](NC(=O)[C@@H](N)Cc1ccccc1)C(=O)N[C@@H](Cc1ccc(O)cc1)C(=O)N[C@@H](CCCCN)C(=O)O",
    "O=C(Nc1ccc(F)cc1)c1ccc2[nH]ncc2c1",
    "COc1ccc(CNc2ncnc3[nH]ccc23)cc1",
    "Cc1cc(Nc2ncnc3sccc23)ccc1Cl",
    "O=C(Nc1cccnc1)c1ccc2nc[nH]c2c1",
    "COc1ccc2nc(N)sc2c1C(=O)Nc1ccccc1",
    "O=C(Nc1ccc(Cl)cc1)c1ccc2[nH]ncc2c1",
    "Cc1ccc(Nc2ncnc3sccc23)cc1",
    "COc1ccc(Nc2ncnc3ccccc23)cc1",
]
# Aspirin — fallback for any SMILES the demo requests but we didn't pre-generate.
FALLBACK_SMILES = "CC(=O)Oc1ccccc1C(=O)O"
SIZE = 220

OUT = Path(__file__).resolve().parents[1] / "apps/web/e2e/_molecule-svgs.generated.ts"


def main() -> None:
    entries = {s: render_svg(s, SIZE, SIZE) for s in SMILES}
    fallback = render_svg(FALLBACK_SMILES, SIZE, SIZE)
    lines = [
        "// GENERATED by scripts/gen_demo_molecule_svgs.py — do not edit by hand.",
        "// Real RDKit 2D depictions (apps/api render_svg, byte-identical to GET /molecule/svg).",
        "// N6: in-silico structures only, no real-world efficacy claim.",
        "export const MOLECULE_SVG_BY_SMILES: Record<string, string> = {",
    ]
    for smiles, svg in entries.items():
        lines.append(f"  {json.dumps(smiles)}: {json.dumps(svg)},")
    lines.append("};")
    lines.append("")
    lines.append(f"export const MOLECULE_SVG_FALLBACK: string = {json.dumps(fallback)};")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT} ({len(entries)} structures + fallback)")


if __name__ == "__main__":
    main()
